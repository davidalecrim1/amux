package setup

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/davidalecrim1/amux/internal/tmux"
)

type Options struct {
	DryRun bool
	Home   string
	Out    io.Writer
}

var claudeEvents = []string{
	"SessionStart",
	"UserPromptSubmit",
	"PreToolUse",
	"PostToolUse",
	"PostToolUseFailure",
	"PermissionRequest",
	"PermissionDenied",
	"Notification",
	"Stop",
	"StopFailure",
	"SessionEnd",
}

func Run(opts Options) error {
	if opts.Out == nil {
		opts.Out = os.Stdout
	}
	home := opts.Home
	if home == "" {
		h, err := os.UserHomeDir()
		if err != nil {
			return err
		}
		home = h
	}
	opts.Home = home
	exe, err := os.Executable()
	if err != nil {
		return err
	}
	if resolved, err := filepath.EvalSymlinks(exe); err == nil {
		exe = resolved
	}

	snippet := filepath.Join(home, ".config", "amux", "tmux.conf")
	tmuxConf := mainTmuxConf(home)
	claudeSettings := filepath.Join(home, ".claude", "settings.json")
	plugin := filepath.Join(home, ".config", "opencode", "plugins", "amux.js")

	fmt.Fprintf(opts.Out, "binary: %s\n\n", exe)

	if err := writeSnippet(snippet, exe, opts); err != nil {
		return err
	}
	if err := ensureSource(tmuxConf, snippet, opts); err != nil {
		return err
	}
	if err := installLiveHooks(exe, opts); err != nil {
		fmt.Fprintf(opts.Out, "tmux hooks: could not apply live (%v); they will load on next config source\n", err)
	}
	if err := mergeClaude(claudeSettings, exe, opts); err != nil {
		return err
	}
	if err := writePlugin(plugin, exe, opts); err != nil {
		return err
	}

	fmt.Fprintln(opts.Out, "")
	if opts.DryRun {
		fmt.Fprintln(opts.Out, "dry run: nothing written")
		return nil
	}
	fmt.Fprintln(opts.Out, "next:")
	fmt.Fprintln(opts.Out, "  tmux source-file ~/.config/amux/tmux.conf   (or reload your tmux config)")
	fmt.Fprintln(opts.Out, "  restart Claude Code so the new hooks load")
	fmt.Fprintln(opts.Out, "  restart OpenCode so the plugin loads")
	return nil
}

func mainTmuxConf(home string) string {
	candidates := []string{
		filepath.Join(home, ".config", "tmux", "tmux.conf"),
		filepath.Join(home, ".tmux.conf"),
	}
	for _, c := range candidates {
		if _, err := os.Stat(c); err == nil {
			return c
		}
	}
	return candidates[0]
}

func snippetContent(exe string) string {
	return fmt.Sprintf(`# Generated by amux setup. Edit amux, not this file.
bind W display-popup -E -w 90%% -h 85%% -T ' amux ' -b rounded '%s pick'
set-hook -g after-select-pane 'run-shell -b "%s focus #{pane_id}"'
set-hook -g after-select-window 'run-shell -b "%s focus #{session_name}:#{window_index}"'
set-hook -g client-session-changed 'run-shell -b "%s focus #{session_name}:#{window_index}"'
`, exe, exe, exe, exe)
}

func writeSnippet(path, exe string, opts Options) error {
	want := snippetContent(exe)
	have, err := os.ReadFile(path)
	if err == nil && string(have) == want {
		fmt.Fprintf(opts.Out, "tmux snippet: unchanged (%s)\n", path)
		return nil
	}
	if opts.DryRun {
		fmt.Fprintf(opts.Out, "tmux snippet: would write %s\n", path)
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(opts.Out, "tmux snippet: wrote %s\n", path)
	return nil
}

func ensureSource(mainConf, snippet string, opts Options) error {
	line := "source-file " + strings.Replace(snippet, opts.Home, "~", 1)
	data, err := os.ReadFile(mainConf)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if strings.Contains(string(data), "amux/tmux.conf") {
		fmt.Fprintf(opts.Out, "tmux config: already sources amux (%s)\n", mainConf)
		return nil
	}
	body := string(data)
	if body != "" && !strings.HasSuffix(body, "\n") {
		body += "\n"
	}
	body += "\n# amux\n" + line + "\n"
	if opts.DryRun {
		fmt.Fprintf(opts.Out, "tmux config: would append %q to %s\n", line, mainConf)
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(mainConf), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(mainConf, []byte(body), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(opts.Out, "tmux config: appended source line to %s\n", mainConf)
	return nil
}

func installLiveHooks(exe string, opts Options) error {
	if opts.DryRun {
		fmt.Fprintln(opts.Out, "tmux hooks: would install after-select-pane, after-select-window, client-session-changed")
		return nil
	}
	hooks := []string{"after-select-pane", "after-select-window", "client-session-changed"}
	for _, h := range hooks {
		if err := tmux.UnsetHooks(h, "amux focus"); err != nil {
			return err
		}
	}
	for _, h := range hooks {
		target := "#{pane_id}"
		if h != "after-select-pane" {
			target = "#{session_name}:#{window_index}"
		}
		command := fmt.Sprintf(`run-shell -b "%s focus %s"`, exe, target)
		if err := tmux.SetHook(h, command); err != nil {
			return err
		}
	}
	fmt.Fprintln(opts.Out, "tmux hooks: installed")
	return nil
}

func mergeClaude(path, exe string, opts Options) error {
	var root map[string]json.RawMessage
	data, err := os.ReadFile(path)
	if err == nil {
		if err := json.Unmarshal(data, &root); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
	} else if errors.Is(err, os.ErrNotExist) {
		root = map[string]json.RawMessage{}
	} else {
		return err
	}
	if root == nil {
		root = map[string]json.RawMessage{}
	}

	hooks := map[string][]json.RawMessage{}
	if raw, ok := root["hooks"]; ok {
		if err := json.Unmarshal(raw, &hooks); err != nil {
			return fmt.Errorf("%s: hooks: %w", path, err)
		}
	}

	added := 0
	for _, event := range claudeEvents {
		cmd := exe + " hook claude " + event
		found := false
		for _, group := range hooks[event] {
			if strings.Contains(string(group), cmd) {
				found = true
				break
			}
		}
		if found {
			continue
		}
		group := fmt.Sprintf(`{"hooks":[{"type":"command","command":%s,"timeout":5}]}`, jsonString(cmd))
		hooks[event] = append(hooks[event], json.RawMessage(group))
		added++
	}
	if added == 0 {
		fmt.Fprintf(opts.Out, "claude hooks: unchanged (%s)\n", path)
		return nil
	}
	if opts.DryRun {
		fmt.Fprintf(opts.Out, "claude hooks: would add %d handlers to %s\n", added, path)
		return nil
	}

	rawHooks, err := json.Marshal(hooks)
	if err != nil {
		return err
	}
	root["hooks"] = rawHooks
	out, err := json.MarshalIndent(root, "", "  ")
	if err != nil {
		return err
	}
	out = append(out, '\n')

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if len(data) > 0 {
		backup := fmt.Sprintf("%s.amux-%s.bak", path, time.Now().Format("20060102-150405"))
		if err := os.WriteFile(backup, data, 0o644); err != nil {
			return err
		}
		fmt.Fprintf(opts.Out, "claude hooks: backup at %s\n", backup)
	}
	if err := os.WriteFile(path, out, 0o644); err != nil {
		return err
	}
	fmt.Fprintf(opts.Out, "claude hooks: added %d handlers to %s\n", added, path)
	return nil
}

func writePlugin(path, exe string, opts Options) error {
	const marker = "// amux: generated by amux setup. Do not edit."
	body := strings.ReplaceAll(pluginTemplate, "__AMUX_BIN__", jsonString(exe))
	body = marker + "\n" + body

	if have, err := os.ReadFile(path); err == nil {
		if string(have) == body {
			fmt.Fprintf(opts.Out, "opencode plugin: unchanged (%s)\n", path)
			return nil
		}
		if !strings.HasPrefix(string(have), marker) {
			fmt.Fprintf(opts.Out, "opencode plugin: %s exists and was not generated by amux; leaving it alone\n", path)
			return nil
		}
	}
	if opts.DryRun {
		fmt.Fprintf(opts.Out, "opencode plugin: would write %s\n", path)
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(opts.Out, "opencode plugin: wrote %s\n", path)
	return nil
}

func jsonString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

const pluginTemplate = `// Reports OpenCode session state to amux (OpenCode v2 plugin API).
import { Plugin } from "@opencode/plugin"
import { spawn } from "node:child_process"

const BIN = __AMUX_BIN__
const pane = process.env.TMUX_PANE
let sessionID = undefined

function report(payload) {
  if (!pane) return
  try {
    const proc = spawn(BIN, ["report"], { detached: true, stdio: ["pipe", "ignore", "ignore"] })
    proc.on("error", () => {})
    proc.stdin.on("error", () => {})
    proc.stdin.end(JSON.stringify({ pane_id: pane, agent: "opencode", ...payload }))
    proc.unref()
  } catch {}
}

function mine(event) {
  const id = event?.properties?.sessionID
  return sessionID === undefined || id === undefined || id === sessionID
}

export default Plugin.define({
  id: "amux",
  async setup(ctx) {
    const controller = new AbortController()

    void (async () => {
      try {
        for await (const event of ctx.event.subscribe({ signal: controller.signal })) {
          if (!mine(event)) continue
          switch (event.type) {
            case "session.idle":
              report({ state: "done_unseen" })
              break
            case "permission.asked":
              report({ state: "needs_input", detail: "permission" })
              break
            case "permission.replied":
              report({ state: "running" })
              break
            case "session.error":
              report({ state: "needs_input", detail: "error" })
              break
            case "session.deleted":
              report({ state: "gone" })
              break
          }
        }
      } catch {}
    })()

    await ctx.session.hook("prompt", (event) => {
      sessionID = event.sessionID
      report({ state: "running" })
    })

    await ctx.tool.hook("execute.before", (event) => {
      report({ state: "running", detail: event.tool })
    })

    return () => controller.abort()
  },
})
`
